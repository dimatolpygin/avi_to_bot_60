#!/bin/sh
# Точка входа контейнера: сначала догнать схему, потом запускать приложение.
# Так «выкатили код с новой миграцией» и «схема поехала» — одно действие,
# а не два, и забыть второе невозможно.
set -e

if [ "${SKIP_MIGRATIONS}" = "1" ]; then
  echo "🗄  Миграции пропущены (SKIP_MIGRATIONS=1)"
else
  echo "🗄  Применяю миграции: alembic upgrade head"
  alembic upgrade head
fi

exec "$@"
