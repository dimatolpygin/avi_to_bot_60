# ── Сборка промпта ───────────────────────────────────────────────────────────

def sobrat(shapka: str, persona: str, kompaniya: str, bloki: list[Blok]) -> str:
    """Промпт услуг из готовых частей: шапка-персона + блоки знаний + правила стиля.

    Чистая функция без БД — на ней держатся и код-фолбэк, и тесты. Правила
    стиля у услуг всегда мужского рода (персона — Роман) и без раздела про
    позиции прайса (`pro_pozicii=False`): прайса у услуг нет.
    """
    telo = "\n\n".join([shapka, *(b.content for b in bloki)])
    stil = pravila_stilya(persona, kompaniya, zhenskiy_rod=False, pro_pozicii=False)
    return f"{telo}\n\n{stil}"


def prompt_iz_koda(kod: str, kompaniya: str) -> str:
    """Код-фолбэк: собрать промпт услуг из встроенных блоков, без БД.

    Используется `profili.py` и как страховка в `core.py`, когда база знаний
    в БД недоступна или ещё не засеяна.
    """
    persona = PERSONY[kod]
    return sobrat(persona.shapka, persona.imya, kompaniya, bloki_akkaunta(kod))


async def prompt_iz_bd(sessiya, kod: str, kompaniya: str) -> str | None:
    """Собрать промпт услуг из БД: `account_prompts` (персона+шапка) и
    `knowledge_blocks` (блоки по `sort`).

    Возвращает None, если база знаний аккаунта пуста, — тогда вызывающий код
    падает на `prompt_iz_koda`. Так правка блока в БД меняет ответ (после
    рестарта, как и обновление каталога), а незасеянная БД не гасит бота.
    """
    from .models import Account, AccountPrompt, KnowledgeBlock

    account_id = await sessiya.scalar(select(Account.id).where(Account.code == kod))
    if account_id is None:
        return None

    bloki_bd = (await sessiya.scalars(
        select(KnowledgeBlock)
        .where(KnowledgeBlock.account_id == account_id, KnowledgeBlock.is_active.is_(True))
        .order_by(KnowledgeBlock.sort, KnowledgeBlock.id)
    )).all()
    if not bloki_bd:
        return None

    ap = (await sessiya.scalars(
        select(AccountPrompt)
        .where(AccountPrompt.account_id == account_id, AccountPrompt.is_active.is_(True))
        .order_by(AccountPrompt.version.desc(), AccountPrompt.id.desc())
    )).first()
    if ap is None:
        # Блоки есть, а шапки нет — берём персону из кода, но текст блоков из БД.
        persona = PERSONY.get(kod)
        if persona is None:
            return None
        shapka, imya = persona.shapka, persona.imya
    else:
        shapka, imya = ap.body, (ap.persona or PERSONY[kod].imya)

    bloki = [Blok(b.key, b.title, b.content) for b in bloki_bd]
    return sobrat(shapka, imya, kompaniya, bloki)
