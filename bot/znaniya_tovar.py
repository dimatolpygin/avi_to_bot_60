def podstavit_bloki(shablon: str, bloki: dict[str, str]) -> str:
    """Подставить тексты блоков в `<<ключ>>` скелета. Лишние ключи игнорируем,
    отсутствующие маркеры не трогаем — так `privetstvie` в карте не мешает."""
    out = shablon
    for key, text in bloki.items():
        out = out.replace(f"<<{key}>>", text)
    return out


