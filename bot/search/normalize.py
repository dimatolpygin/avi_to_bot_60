# -*- coding: utf-8 -*-
"""Нормализация и стемминг запросов и названий (этап 5).

Перенос из референса telewin (`bot/search/normalize.py`), где эта тройка
функций обкатана на 12 000 позиций. Что здесь важно и почему:

* **Стеммер — snowball russian**, не «отрезать окончание». В telewin замена
  наивного стеммера на snowball дала +7% top-1: «вагонки», «вагонку»,
  «вагонке» сходятся в один стем, а «вагонная» — нет.
* **Гомоглифы латиница→кириллица.** Клиент пишет «сорт A» латинской A, прайс —
  кириллической. На глаз одинаково, для `==` это разные строки.
* **`soft_has`** связывает сокращения прайса с полными формами клиента:
  «алюмин.» ↔ «алюминиевая». Порог 4 символа — ниже начинается мусор
  («печ» ↔ «печать»).

Разделение труда с `bot/etl/razbor.py`: тот разбирает НАЗВАНИЯ ПРАЙСА (канон
заказчика, регистр сохраняется для показа клиенту), этот — ЖИВУЮ РЕЧЬ клиента
(регистр не нужен, важна сводимость форм).
"""
from __future__ import annotations

import re
import unicodedata

import snowballstemmer

_st = snowballstemmer.stemmer("russian")

# Латинские гомоглифы → кириллица: «сорт A» ↔ «сорт А», «STS» остаётся как есть
# (там латиница осмысленная, но и в прайсе она латиницей — сравнение сойдётся).
_GOMO = str.maketrans("acekmopxyABCEKMHOPTXY", "асекморхуАВСЕКМНОРТХУ")

# Стоп-слова: связки и «коммерческий шум», который есть в каждом втором запросе
# («сколько стоит вагонка», «нужна дверь»). В стемы не идут — иначе два запроса
# про разные товары выглядят похожими из-за общих «стоит» и «нужно».
_STOP = {
    "и", "а", "в", "во", "на", "по", "для", "с", "со", "от", "до", "у", "за",
    "из", "к", "ко", "о", "об", "про", "при",
    "или", "же", "ли", "бы", "не", "ещё", "еще", "как", "так", "это", "вот",
    "есть", "нужен", "нужна", "нужны", "нужно", "надо", "хочу", "хотел",
    "сколько", "стоит", "стоимость", "цена", "цену", "цены", "почем", "почём",
    "руб", "рубль", "рублей", "что", "какой", "какая", "какие", "мне", "вы",
    "меня", "вас", "подскажите", "скажите", "здравствуйте", "добрый", "день",
    "пожалуйста", "спасибо", "the",
}

_TOKEN = re.compile(r"[а-яa-z0-9][а-яa-z0-9.,/-]*")


def norm(s: str) -> str:
    """Нижний регистр, ё→е, латинские гомоглифы→кириллица, схлопнутые пробелы.

    NFKC и неразрывный пробел — не паранойя: текст приходит из Telegram и Авито,
    где встречается и то и другое, а `«вагонка\xa0липа» != «вагонка липа»`.
    """
    s = unicodedata.normalize("NFKC", str(s)).replace("\xa0", " ")
    s = s.lower().replace("ё", "е").translate(_GOMO)
    return re.sub(r"\s+", " ", s).strip()


def slova(s: str) -> list[str]:
    """Нормализованные слова БЕЗ стемминга — вход фаззи-канала.

    Опечатки ловятся именно здесь: у «вогонка» и «вагонка» сходство 0.86,
    а у их стемов («вогонк»/«вагонк») уже 0.83 — порог 0.85 стем не переживёт.
    Поэтому фаззи работает со словами, а точное совпадение — со стемами.
    """
    out = []
    for t in _TOKEN.findall(norm(s)):
        t = t.strip(".,-/")
        if t and t not in _STOP:
            out.append(t)
    return out


def stems(s: str) -> set[str]:
    """Множество стемов: словоформы клиента сводятся к формам прайса."""
    return {_st.stemWord(t) for t in slova(s)}


def stem_slova(w: str) -> str:
    """Стем одного слова (для ключей словарей, которые матчатся по стему)."""
    return _st.stemWord(norm(w))


def soft_has(stem_set: set[str], w: str) -> bool:
    """Мягкое совпадение слова с множеством стемов: точное ИЛИ один — префикс
    другого (минимум 4 символа). Связывает сокращения прайса с полными формами
    клиента: «алюмин.» ↔ «алюминиевая», «профилир.» ↔ «профилированный».

    Порог 4 обязателен: без него «печ» цепляется за «печать», а «дуб» —
    за «дубликат». Порт `softHas` из telewin.
    """
    if w in stem_set:
        return True
    if len(w) < 4:
        return False
    for x in stem_set:
        if len(x) < 4:
            continue
        korotkoe, dlinnoe = (x, w) if len(x) < len(w) else (w, x)
        if dlinnoe.startswith(korotkoe):
            return True
    return False
