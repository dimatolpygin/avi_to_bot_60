# -*- coding: utf-8 -*-
"""Постобработка стиля ответа (этап 8).

**Тире «—» и markdown чистим КОДОМ, а не промптом.** Промпт задаёт тон,
но гарантии не даёт: модель всё равно иногда проставит длинное тире или
`**жирный**`, даже когда прямо запрещено. Это правило заказчика, и держится
оно на регэкспах, а не на послушании модели.

Чистится не только то, что уходит клиенту, но и то, что ложится в историю
диалога: иначе на следующем ходу модель скопирует собственный прежний формат
и вернёт разметку обратно.

Что НЕ трогаем: цифры. Постобработка работает с готовым текстом реплики,
цены приходят из инструмента и правятся только там.
"""
from __future__ import annotations

import re

# «10 — 15» → «10-15»: между числами тире значит диапазон, и запятая его сломает.
_TIRE_MEZHDU_CHISEL = re.compile(r"(\d)\s*[—–]\s*(\d)")
_TIRE_MEZHDU_SLOV = re.compile(r"\s*[—–]\s*")
# Граница предложения — для правила «несколько тире в одном предложении».
# Скобки обязательны: со скобками `split` отдаёт разделители вперемешку
# с кусками, и текст склеивается обратно ровно таким, каким был.
_PO_PREDLOZHENIYAM = re.compile(r"((?<=[.!?…])\s+|\n+)")
_ZHIRNYY = re.compile(r"\*\*(.+?)\*\*|__(.+?)__")
_KURSIV = re.compile(r"(?<!\*)\*(?!\s)(.+?)(?<!\s)\*(?!\*)")
_ZAGOLOVOK = re.compile(r"^\s{0,3}#{1,6}\s*", re.M)
_MARKER_SPISKA = re.compile(r"^\s{0,3}(?:[-*•]|\d{1,2}[.)])\s+", re.M)
# Пустая строка внутри реплики — это разбиение на абзацы, то есть карточка товара,
# а не сообщение в мессенджере. Модель делает так вопреки промпту, поэтому склеиваем
# кодом: абзацы становятся строками одного ответа.
_PUSTYE_STROKI = re.compile(r"\n\s*\n+")
_PROBELY = re.compile(r"[ \t]{2,}")

# Эмодзи: основные диапазоны пиктограмм. Метки логов (👤 🔧 🧠 🤖) сюда не попадают —
# они живут в логе, а не в тексте реплики.
_EMODZI = re.compile(
    "[\U0001F300-\U0001FAFF\U00002600-\U000027BF\U0001F1E6-\U0001F1FF️⭐❤]")


# Приветствие в начале реплики: «Здравствуйте, это Александра из Saunamart.»
# Ловим только ПЕРВОЕ предложение и только если оно начинается с приветствия —
# «Здравствуйте» в середине ответа («вам ответят: здравствуйте…») не трогаем.
_PRIVETSTVIE = re.compile(
    r"^\s*(?:здравствуйте|добрый день|доброе утро|добрый вечер|приветствую|доброго дня)"
    r"[^.!?\n]{0,120}[.!?]+\s*", re.I)


def snyat_privetstvie(tekst: str) -> str:
    """Убрать повторное приветствие из начала реплики.

    Нужно, потому что бот здоровается ДВАЖДЫ, и промптом это не лечится.
    Механика: на `/start` клиент получает стартовое сообщение из брифа заказчика
    («Вас приветствует компания Saunamart. Меня зовут Александра…»), оно ложится
    в историю. На первый же вопрос модель видит там своё сообщение, но НЕ узнаёт
    в нём предписанную формулировку («Здравствуйте, это Александра из Saunamart»)
    и здоровается заново. Поймано на живом прогоне 23.07.

    Если кроме приветствия в реплике ничего нет, оставляем как есть: лучше лишнее
    «здравствуйте», чем пустое сообщение.
    """
    if not tekst:
        return tekst
    ostatok = _PRIVETSTVIE.sub("", tekst, count=1).lstrip()
    return ostatok or tekst


def _ubrat_tire(tekst: str) -> str:
    """Тире вон, но не любой ценой запятой.

    Заказчик запретил длинные тире, и в лоб это делалось заменой на запятую.
    На живом диалоге 23.07 вылезла цена такой прямолинейности: модель пишет
    перечисление через тире («Сорт А — без сучков, Экстра — идеальный вид,
    В — с сучками»), и после замены получается каша, в которой не видно, где
    название, а где описание.

    Поэтому исключение: если тире в предложении НЕСКОЛЬКО, это перечисление,
    и каждая новая запятая делает его нечитаемым — выкидываем их все.

    Одиночное тире по-прежнему становится запятой: «Липа три метра, 513 рублей».
    Выкидывать и его (даже перед связкой, «метр — это длина») пробовали
    и откатили: на живом прогоне 23.07 это дало обрывок «мы не делаем это
    не наш формат». Слева от тире не всегда подлежащее, и без запятой две
    части фразы слипаются в бессмыслицу — запятая тут страхует.
    """
    tekst = _TIRE_MEZHDU_CHISEL.sub(r"\1-\2", tekst)
    # Считаем тире по предложениям, а не по всему ответу: два предложения, в каждом
    # по одному тире, — это две обычные фразы, а не перечисление. Разделители
    # `split` возвращает вместе с кусками (группа в скобках), поэтому текст
    # склеивается обратно без потерь.
    chasti = _PO_PREDLOZHENIYAM.split(tekst)
    return "".join(_bez_tire(ch) if i % 2 == 0 else ch
                   for i, ch in enumerate(chasti))


def _bez_tire(predlozhenie: str) -> str:
    """Одно тире → запятая, несколько → просто выкинуть."""
    skolko = len(_TIRE_MEZHDU_SLOV.findall(predlozhenie))
    if skolko == 0:
        return predlozhenie
    return _TIRE_MEZHDU_SLOV.sub(" " if skolko > 1 else ", ", predlozhenie)


# Просьба дать телефон. Ловим ПРЕДЛОЖЕНИЕ, в котором есть и слово про контакт,
# и глагол-просьба: «оставите номер телефона?», «напишите ваш телефон», «нужны
# ваши контакты». Без глагола не срабатываем — «спасибо, записала ваш номер»
# и «позвоним на этот номер» это не просьба, а подтверждение.
_PRO_KONTAKT = re.compile(r"(номер|телефон|контакт|whatsapp|ватсап)", re.I)
_PROSBA = re.compile(
    r"(остав(ь|и|ите|ляйте)?|напиш(и|ите)|скаж(и|ите)|да(й|йте)|подскаж(и|ите)|"
    r"укаж(и|ите)|пришл(и|ите)|нужен|нужны|нужно|можете\s+оставить)",
    re.I)
# Просьба без слова «телефон»: слов про контакт в ней нет, а смысл тот же.
_PROSBA_BEZ_SLOVA = re.compile(
    r"(как\s+(с\s+вами\s+связаться|вас\s+найти|вам\s+удобно\s+связаться)|"
    r"куда\s+(вам\s+)?(позвонить|написать))", re.I)


def est_proshba_telefona(tekst: str) -> bool:
    """Есть ли в реплике просьба дать контакт. Нужна, чтобы понять, просили ли
    уже раньше в этом диалоге: один раз можно, второй — нет."""
    if not tekst:
        return False
    for i, ch in enumerate(_PO_PREDLOZHENIYAM.split(tekst)):
        if i % 2 == 0 and _eto_proshba(ch):
            return True
    return False


def _eto_proshba(predlozhenie: str) -> bool:
    return bool((_PRO_KONTAKT.search(predlozhenie) and _PROSBA.search(predlozhenie))
                or _PROSBA_BEZ_SLOVA.search(predlozhenie))


def snyat_proshbu_telefona(tekst: str) -> tuple[str, str | None]:
    """Убрать из ответа ПОВТОРНУЮ просьбу дать телефон. → (текст, что вырезали).

    Тонкий баланс, и обе крайности плохи. Клянчить контакт вместо ответа —
    баг №1 старого бота (`04_баги_старого_бота.md`). Но не спросить вообще —
    значит не получить лид: клиент думает, что уже говорит с менеджером
    в чате, и телефон ему оставлять незачем. Тогда в amoCRM не уйдёт ничего,
    а ради этого всё и делается.

    Поэтому спросить можно РОВНО ОДИН раз за переписку, когда клиент созрел.
    Момент выбирает модель по промпту, а код держит счёт: решает не эта функция,
    а вызывающий — он смотрит, просили ли уже в истории диалога.

    Режем ровно предложение с просьбой, остальной ответ остаётся: клиенту нужен
    ответ про товар, а не пустое сообщение. Если кроме просьбы в реплике ничего
    нет, отдаём как было — пусть лучше спросит, чем промолчит.
    """
    if not tekst:
        return tekst, None
    chasti = _PO_PREDLOZHENIYAM.split(tekst)
    ostalos, vyrezano = [], []
    for i, ch in enumerate(chasti):
        if i % 2 == 0 and _eto_proshba(ch):
            vyrezano.append(ch.strip())
            continue
        ostalos.append(ch)
    if not vyrezano:
        return tekst, None
    chistyy = "".join(ostalos).strip()
    if not chistyy:
        return tekst, None
    return chistyy, " ".join(vyrezano)


def ochistit_otvet(tekst: str) -> str:
    """Убрать тире, markdown и эмодзи, вернуть живой текст. Идемпотентна."""
    if not tekst:
        return tekst
    tekst = _ubrat_tire(tekst)
    tekst = _ZHIRNYY.sub(lambda m: m.group(1) or m.group(2), tekst)
    tekst = _KURSIV.sub(r"\1", tekst)
    tekst = _ZAGOLOVOK.sub("", tekst)
    tekst = _MARKER_SPISKA.sub("", tekst)
    tekst = _EMODZI.sub("", tekst)
    # Подчистка артефактов замены тире на запятую.
    tekst = re.sub(r"^\s*,\s*", "", tekst, flags=re.M)
    tekst = re.sub(r"\s+,", ",", tekst)
    tekst = re.sub(r",\s*,", ",", tekst)
    tekst = _PUSTYE_STROKI.sub("\n", tekst)
    tekst = _PROBELY.sub(" ", tekst)
    return tekst.strip()
