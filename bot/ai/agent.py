def _assortiment(katalog: Katalog) -> str:
    """Строки ассортимента для промпта: канон семейства + сколько видов.

    Собирается ИЗ КАТАЛОГА, а не пишется руками: прайс меняется, и список,
    зашитый в текст, начнёт врать первым. Цен здесь нет намеренно — за ценой
    модель обязана идти в инструмент.
    """
    sl = slovari()
    stroki = []
    for family, gruppy in sorted(katalog.po_semeystvu.items()):
        if not family:
            continue
        sem = sl.semeystva.get(family)
        nazvanie = (sem.kanon if sem and sem.kanon else family)
        vidov = len(gruppy)
        stroki.append(f"- {nazvanie}" + (f" ({vidov} вида)" if vidov > 1 else ""))
    return "\n".join(stroki)


def sobrat_prompt(katalog: Katalog, bloki: dict[str, str] | None = None) -> str:
    """Системный промпт Saunamart: скелет-механика + редактируемые блоки + каталог.

    `bloki` — тексты блоков из БД (правки заказчика во вкладке «Saunamart (1)»,
    этап 19 Шаг 2). Отсутствующие ключи добираются из код-фолбэка, поэтому
    неполный набор в БД не оставляет `<<ключ>>` в промпте. `bloki=None` → чистый
    код-фолбэк, и результат байт-в-байт равен монолиту до Шага 2 (golden-тест).
    """
    sist = (SISTEMNY if not bloki
            else podstavit_bloki(SISTEMNY_SHABLON, {**_BLOKI_PO_UMOLCHANIYU, **bloki}))
    return (sist
            .replace("{ПРАВИЛА_СТИЛЯ}", pravila_stilya("Александра", "Saunamart"))
            .replace("{АССОРТИМЕНТ}", _assortiment(katalog)))


# ── Предохранитель ───────────────────────────────────────────────────────────

# Маркеры отказа: и «товара нет», и категорийное «не наш профиль». Оба на первом
# ходу без поиска подозрительны: модель может отнести реальную позицию прайса
# к непрофильному и отказать по памяти.
_RE_OTKAZ = re.compile(
    r"не найд|не нашл|нет в (?:прайсе|каталоге|наличии|ассортимент)|отсутству|"
    r"не удалось найти|не прода[её]м|не торгуем|не занимаемся|не наш профиль|"
    r"нет так(?:ого|ой)|у нас нет|не вход(?:ит|ят) в ассортимент",
    re.I,
)


def _zayavil_otkaz(tekst: str) -> bool:
    """Ответ модели — отказ, а не показ товара и не уточняющий вопрос."""
    return bool(_RE_OTKAZ.search(tekst))


# Светская реплика: товара в ней нет, форсировать по ней поиск бессмысленно.
_RE_BOLTOVNYA = re.compile(
    r"^\W*(привет|здравств|добрый|доброе|хай|салют|спасибо|благодар|пока\b|до свидан|"
    r"ок\b|окей|хорошо|ага|да\b|нет\b|как дела|кто ты|ты бот|/start|/reset|/help)",
    re.I,
)


def _boltovnya(tekst: str) -> bool:
    t = tekst.strip()
    return len(t) < 40 and bool(_RE_BOLTOVNYA.match(t))


def _zadala_vopros(tekst: str) -> bool:
    return "?" in tekst


def _uzhe_prosili_kontakt(istoriya: list[dict]) -> bool:
    """Просил ли бот телефон раньше в этом диалоге.

    Один раз — рабочий приём, второй — выпрашивание. Считаем по истории,
    а не по флагу в памяти: история и так едет с каждым ходом, а лишнее
    состояние пришлось бы хранить в Redis и синхронизировать с отменами
    реплик (этап 9 умеет их отменять, и «просили» тогда было бы враньём).
    """
    return any(z.get("role") == "assistant" and est_proshba_telefona(z.get("content", ""))
               for z in istoriya)


def _bot_uzhe_govoril(istoriya: list[dict]) -> bool:
    """Была ли в этом диалоге хоть одна реплика бота — включая приветствие,
    отправленное транспортом в обход модели."""
    return any(z.get("role") == "assistant" for z in istoriya)


