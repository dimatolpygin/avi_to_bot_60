def _chislo(d: Decimal | None) -> float | int | None:
    """Decimal → число для JSON. Целое отдаём целым, иначе модель напишет «513.0 рублей»."""
    if d is None:
        return None
    return int(d) if d == d.to_integral_value() else float(d)


def _rubli(d: Decimal | None) -> int | None:
    """Цена → целые рубли.

    Вычисленные цены (за метр, за квадрат) хранятся с копейками: 371 / 3.0 даёт
    123.67. Отдать это модели значит услышать от неё «сто двадцать три рубля
    шестьдесят семь копеек» — живой менеджер копейки не называет, и в прайсе
    их тоже нет. Округляем в момент выдачи, а не в хранении: копейки нужны,
    чтобы вычисление сходилось, но не нужны в реплике.
    """
    if d is None:
        return None
    return int(d.quantize(Decimal("1"), rounding=ROUND_HALF_UP))


