def payload_poiska(nahodki: list[Nahodka], kanal: str, data_praysa: str,
                   pod_obyavleniem: bool = False) -> dict:
    payload: dict = {"дата_актуальности_прайса": data_praysa, "канал_поиска": kanal}
    if not nahodki:
        payload["найдено"] = []
        if pod_obyavleniem and kanal != "чужой домен":
            payload["пометка"] = PUSTO_POD_OBYAVLENIEM
        else:
            payload["пометка"] = PUSTO_PO_KANALU.get(
                kanal, PUSTO_PO_KANALU["не найдено"])
        return payload
    payload["найдено"] = [_pozitsiya_v_payload(n) for n in nahodki]
    return payload


# ── Agent-loop ───────────────────────────────────────────────────────────────


@dataclass
class OtvetAgenta:
    otvet: str
    istoriya: list[dict]
    zaprosy_poiska: list[str] = field(default_factory=list)
    naydeno: int = 0
    forsirovan_poisk: bool = False
    lead_peredan: bool = False


async def otvetit(cfg: OpenRouterConfig, poisk: Poisk | None, istoriya: list[dict],
                  tekst_klienta: str, data_praysa: str = "",
                  sistemny: str | None = None,
                  peredat_lead=None, peredat_dialog=None,
                  pod_obyavleniem: bool = False) -> OtvetAgenta:
    """Ответ на реплику клиента.

    `istoriya` — предыдущие реплики диалога (`role`/`content`); хранит её
    диспетчер этапа 9, сюда она просто передаётся. **Промежуточные tool-сообщения
    в историю НЕ кладём**: клиенту они не видны, а модели на следующем ходу мешают —
    она начинает пересказывать старую выдачу вместо нового поиска.

    `poisk=None` — аккаунт БЕЗ прайса (два аккаунта услуг, этап 10). Инструмент
    тогда не даём вовсе: с пустым каталогом он на любой вопрос отвечал бы «не найдено»,
    и бот отделки говорил бы клиенту, что такой позиции нет. Предохранители тоже
    выключаются — они про то, что модель отказала, не заглянув в прайс, а прайса нет.

    `peredat_lead(телефон, имя, выжимка)` — куда отдать контакт, когда клиент
    сам его оставил. Инструмент `save_lead` есть у ВСЕХ аккаунтов, включая
    услуги: прайса у них нет, а контакт есть всегда.

    `pod_obyavleniem` (Авито) — клиент пишет под активным объявлением. Меняет
    пометку пустой выдачи «не найдено»: под объявлением товар в продаже, поэтому
    «уточню у поставщика»/«нет в прайсе» не говорим (см. `PUSTO_POD_OBYAVLENIEM`).
    «Чужой домен» это не смягчает.
    """
    if sistemny is None:
        if poisk is None:
            raise ValueError("Без поиска системный промпт обязателен: "
                             "у аккаунта услуг его собирать не из чего")
        sistemny = sobrat_prompt(poisk.katalog)
    # Поиск — только у товарного аккаунта; save_lead и передача менеджеру — у всех.
    instrumenty = ([*INSTRUMENTY, INSTRUMENT_LEAD] if poisk is not None
                   else [INSTRUMENT_LEAD])
    instrumenty = [*instrumenty, INSTRUMENT_PEREDACHA]
    soobshcheniya: list[dict] = [
        {"role": "system", "content": sistemny},
        *istoriya,
        {"role": "user", "content": tekst_klienta},
    ]
    zaprosy_poiska: list[str] = []
    naydeno = 0
    lead_peredan = False
    dialog_peredan = False   # передан ли диалог менеджеру за этот ход (14.11)
    forsirovano = False      # предохранитель срабатывает не больше раза за ход
    forsim_seychas = False

    for _ in range(ITERACIY):
        # Форсируем ИМЕННО поиск, а не «любой инструмент»: с появлением save_lead
        # значение "required" разрешило бы модели вместо прайса дёрнуть передачу
        # лида — то есть предохранитель начал бы просить телефон вместо поиска.
        rezultat = await chat(cfg, soobshcheniya, instrumenty,
                              tool_choice=FORSIROVAT_POISK if forsim_seychas else "auto")
        forsim_seychas = False

        if rezultat.get("tool_calls"):
            soobshcheniya.append({"role": "assistant",
                                  "content": rezultat.get("content") or "",
                                  "tool_calls": rezultat["tool_calls"]})
            for vyzov in rezultat["tool_calls"]:
                imya_instrumenta = vyzov.get("function", {}).get("name", "")

                if imya_instrumenta == "save_lead":
                    otvet_instrumenta = await _peredat_lead(vyzov, peredat_lead)
                    lead_peredan = lead_peredan or otvet_instrumenta.get("передан", False)
                    soobshcheniya.append({
                        "role": "tool", "tool_call_id": vyzov["id"],
                        "content": json.dumps(otvet_instrumenta, ensure_ascii=False),
                    })
                    continue

                if imya_instrumenta == "peredat_menedzheru":
                    # Даётся всем аккаунтам (в т.ч. услугам без поиска), поэтому
                    # обрабатываем ДО ветки «инструмента нет». Повторный вызов за один
                    # ход — no-op: одна передача на реплику достаточно.
                    otvet_instrumenta = await _peredat_dialog(
                        vyzov, peredat_dialog, uzhe=dialog_peredan)
                    dialog_peredan = dialog_peredan or otvet_instrumenta.get("передан", False)
                    soobshcheniya.append({
                        "role": "tool", "tool_call_id": vyzov["id"],
                        "content": json.dumps(otvet_instrumenta, ensure_ascii=False),
                    })
                    continue

                # Поиска нет (аккаунт услуг), а модель его всё же позвала —
                # отвечаем инструментом, а не падаем: инструмент ей не давали,
                # значит это выдумка провайдера, и диалог из-за неё рваться не должен.
                if poisk is None:
                    log_oshibka(f"Модель позвала «{imya_instrumenta}», которого у неё нет")
                    soobshcheniya.append({
                        "role": "tool", "tool_call_id": vyzov["id"],
                        "content": json.dumps(
                            {"ошибка": "Такого инструмента нет. Ответь текстом."},
                            ensure_ascii=False),
                    })
                    continue

                zapros, assort = _razobrat_vyzov(vyzov)
                zaprosy_poiska.append(zapros)
                top = TOP_ASSORTIMENT if assort else TOP_TOCHECHNY
                nahodki, kanal = poisk.iskat(zapros, top=top)
                naydeno = len(nahodki)
                log_tool_call("search_products",
                              {"query": zapros, "assortiment": assort, "канал": kanal},
                              f"{naydeno} позиций")
                soobshcheniya.append({
                    "role": "tool", "tool_call_id": vyzov["id"],
                    "content": json.dumps(
                        payload_poiska(nahodki, kanal, data_praysa, pod_obyavleniem),
                        ensure_ascii=False),
                })
            continue

        otvet = (rezultat.get("content") or "").strip()
        if not otvet:
            # Модель изредка отдаёт пустой content без вызова инструмента. Заглушка
            # была бы враньём: данные уже есть, просто реплика не сгенерировалась.
            logger.warning("Пустой ответ модели — повторяю итерацию")
            soobshcheniya.append({"role": "system",
                                  "content": "Ответь покупателю текстом по уже полученным данным."})
            continue

        # ПРЕДОХРАНИТЕЛЬ: модель отказала, ни разу не заглянув в прайс. Не отдаём
        # такой ответ клиенту — форсируем реальный поиск и переотвечаем.
        if (poisk is not None and not zaprosy_poiska and not forsirovano
                and _zayavil_otkaz(otvet)):
            forsirovano = True
            forsim_seychas = True
            logger.warning("🧯 Агент отказал без поиска — форсирую search_products")
            soobshcheniya.append({"role": "system", "content":
                                  "Ты не проверила прайс. Обязательно вызови search_products "
                                  "по товару из вопроса покупателя, прежде чем говорить о наличии."})
            continue

        # ПРЕДОХРАНИТЕЛЬ ВТОРОЙ: модель задала уточняющий вопрос, ни разу не заглянув
        # в прайс, — значит варианты в вопросе взяты из общих знаний, а не из нашего
        # ассортимента. Поймано на живом прогоне: на «почём квадратный метр вагонки
        # липа» модель спросила «какой сорт, А, В, С или эконом?», хотя сортов у нас
        # три и никаких «С» и «эконом» не существует. Промптом это не гарантируется.
        if (poisk is not None and not zaprosy_poiska and not forsirovano
                and _zadala_vopros(otvet) and not _boltovnya(tekst_klienta)):
            forsirovano = True
            forsim_seychas = True
            logger.warning("🧯 Агент уточняет без поиска — форсирую search_products")
            soobshcheniya.append({"role": "system", "content":
                                  "Не спрашивай покупателя, не заглянув в прайс. Вызови "
                                  "search_products по товару из его вопроса и уточняй "
                                  "ТОЛЬКО по тем видам, сортам и длинам, которые реально "
                                  "есть в выдаче."})
            continue

        otvet = ochistit_otvet(otvet)
        # Бот уже говорил в этом диалоге — второе «здравствуйте» снимаем кодом.
        # Промпт это не гарантирует: на `/start` уходит стартовое сообщение из
        # брифа, модель не узнаёт в нём предписанную формулировку и здоровается
        # заново. Проверено на живом диалоге 23.07.
        if _bot_uzhe_govoril(istoriya):
            otvet = snyat_privetstvie(otvet)
        # ПРЕДОХРАНИТЕЛЬ ТРЕТИЙ: ПОВТОРНАЯ просьба дать телефон. Один раз спросить
        # можно и нужно — иначе лид не появится вовсе: клиент считает, что уже
        # говорит с менеджером, и телефон ему оставлять незачем. А вот второй раз
        # — это уже клянчанье, баг №1 старого бота. Момент первой просьбы выбирает
        # модель по промпту, счёт держит код.
        if not lead_peredan and _uzhe_prosili_kontakt(istoriya):
            otvet, vyrezano = snyat_proshbu_telefona(otvet)
            if vyrezano:
                logger.warning("🧯 Агент просил телефон второй раз — вырезал: %s", vyrezano)
        return OtvetAgenta(
            otvet=otvet,
            istoriya=[*istoriya,
                      {"role": "user", "content": tekst_klienta},
                      {"role": "assistant", "content": otvet}],
            zaprosy_poiska=zaprosy_poiska, naydeno=naydeno,
            forsirovan_poisk=forsirovano, lead_peredan=lead_peredan,
        )

    logger.warning("Агент исчерпал лимит итераций (%d)", ITERACIY)
    otvet = "Уточните, пожалуйста, что именно нужно, я подберу по прайсу."
    return OtvetAgenta(
        otvet=otvet,
        istoriya=[*istoriya,
                  {"role": "user", "content": tekst_klienta},
                  {"role": "assistant", "content": otvet}],
        zaprosy_poiska=zaprosy_poiska, naydeno=naydeno, forsirovan_poisk=forsirovano,
        lead_peredan=lead_peredan,
    )


async def _peredat_lead(vyzov: dict, peredat_lead) -> dict:
    """Вызов `save_lead` → передача контакта наружу и ответ модели.

    Наружу лид уходит колбэком, а не прямой записью в БД: `agent.py` про базу
    не знает и знать не должен — он собирает промпт и ведёт agent-loop. Колбэк
    подставляет `bot/core.py`, где известны аккаунт и чат.

    Колбэка нет (тесты, `bot.ai.probe`) — лид не теряем молча, а пишем в лог:
    это единственное событие диалога, которое стоит денег заказчику.
    """
    try:
        args = json.loads(vyzov["function"]["arguments"])
    except (json.JSONDecodeError, KeyError, TypeError):
        log_oshibka("Битые аргументы save_lead — лид не передан")
        return {"передан": False, "ошибка": "Аргументы не разобраны, позови ещё раз."}

    telefon = (args.get("telefon") or "").strip()
    imya = (args.get("imya") or "").strip() or None
    vyzhimka = (args.get("vyzhimka") or "").strip()
    if not telefon:
        return {"передан": False,
                "ошибка": "Телефона нет. Инструмент зовут, только когда клиент дал номер."}

    log_tool_call("save_lead", {"телефон": telefon, "имя": imya}, "передаю менеджеру")
    if peredat_lead is None:
        log_lead(None, telefon, imya, vyzhimka)
        return {"передан": True, "пометка": "Скажи клиенту, что записала и мы свяжемся."}
    try:
        await peredat_lead(telefon, imya, vyzhimka)
    except Exception as e:  # noqa: BLE001 — лид важнее, чем красивый traceback наружу
        log_oshibka(f"Лид не передан ({telefon}): {e}")
        return {"передан": False, "пометка": "Всё равно скажи клиенту, что мы свяжемся."}
    return {"передан": True, "пометка": "Скажи клиенту, что передала менеджеру."}


async def _peredat_dialog(vyzov: dict, peredat_dialog, *, uzhe: bool) -> dict:
    """Вызов `peredat_menedzheru` → передача горячего диалога наружу (14.11).

    Как и лид, уходит колбэком (`bot/core.py`): agent.py про CRM не знает. Телефон
    здесь НЕ участвует — передаём сам факт готовности клиента и выжимку. Повтор за
    один ход глушим (`uzhe`): одной передачи на реплику достаточно.
    """
    if uzhe:
        return {"передан": True, "пометка": "Уже передала, просто ответь клиенту."}
    try:
        args = json.loads(vyzov["function"]["arguments"])
    except (json.JSONDecodeError, KeyError, TypeError):
        log_oshibka("Битые аргументы peredat_menedzheru — диалог не передан")
        return {"передан": False, "ошибка": "Аргументы не разобраны, позови ещё раз."}

    prichina = (args.get("prichina") or "").strip() or "клиент готов к разговору"
    vyzhimka = (args.get("vyzhimka") or "").strip()

    log_tool_call("peredat_menedzheru", {"причина": prichina}, "передаю диалог менеджеру")
    if peredat_dialog is None:
        logger.info("🤝 ПЕРЕДАЧА МЕНЕДЖЕРУ (без телефона) · %s | %s", prichina, vyzhimka)
        return {"передан": True, "пометка": "Скажи клиенту, что подключаешь коллегу и с ним свяжутся."}
    try:
        await peredat_dialog(prichina, vyzhimka)
    except Exception as e:  # noqa: BLE001 — передача не роняет ответ клиенту
        log_oshibka(f"Диалог не передан менеджеру ({prichina}): {e}")
        return {"передан": False, "пометка": "Всё равно скажи клиенту, что подключаешь коллегу."}
    return {"передан": True, "пометка": "Скажи клиенту, что подключаешь коллегу и с ним свяжутся."}


def _razobrat_vyzov(vyzov: dict) -> tuple[str, bool]:
    """Аргументы tool-call. Модель изредка отдаёт битый JSON — не роняем диалог."""
    try:
        args = json.loads(vyzov["function"]["arguments"])
        return args.get("query", ""), bool(args.get("assortiment", False))
    except (json.JSONDecodeError, KeyError, TypeError):
        logger.warning("Битые аргументы tool-call: %s", vyzov)
        return "", False
